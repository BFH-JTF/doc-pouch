import type {McpServer} from '@modelcontextprotocol/sdk/server/mcp.js';
import NeDbWrapper from '../../NeDbWrapper.js';
import SchemaValidator from '../../SchemaValidator.js';
import type winston from 'winston';
import EmailService, {passwordInResponseAllowed} from '../../EmailService.js';
import {generatePassword} from '../../passwordGenerator.js';
import {
    WhoamiSchema,
    ListUsersSchema,
    GetUserSchema,
    CreateUserSchema,
    UpdateUserSchema,
    DeleteUserSchema,
    ForgotPasswordSchema,
    ResetPasswordSchema,
    AdminResetPasswordSchema,
} from '../schemas.js';
import {mcpAuthContext} from '../context.js';
import {getErrorMessage} from '../utils.js';

function getUserId(): string | null {
    const store = mcpAuthContext.getStore();
    return store?.userid ?? null;
}

export function registerUserTools(
    server: McpServer,
    dataManager: NeDbWrapper,
    logger: winston.Logger,
    validator: SchemaValidator,
    emailService: EmailService,
): void {
    server.registerTool('whoami', {
        description: 'Return the authenticated docPouch user\'s profile information.',
        inputSchema: WhoamiSchema,
    }, async () => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const user = await dataManager.getUserByID(userid);
            const {password: _, ...safe} = user as any;
            return {content: [{type: 'text', text: JSON.stringify(safe)}]};
        } catch (error: unknown) {
            logger.error(`MCP whoami error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('list_users', {
        description: 'List all docPouch users. Admin only; non-admin users receive only their own profile.',
        inputSchema: ListUsersSchema,
    }, async () => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const users = await dataManager.getUsers(userid);
            const safe = users.map((u: any) => {
                const {password: _, ...rest} = u;
                return rest;
            });
            return {content: [{type: 'text', text: JSON.stringify(safe)}]};
        } catch (error: unknown) {
            logger.error(`MCP list_users error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('get_user', {
        description: 'Get a docPouch user by ID. Admin only; regular users can only view themselves.',
        inputSchema: GetUserSchema,
    }, async (args) => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const isAdmin = await dataManager.isAdmin(userid);
            if (!isAdmin && args.id !== userid) {
                return {
                    content: [{type: 'text', text: 'Error: admin access required to view other users'}],
                    isError: true
                };
            }
            const user = await dataManager.getUserByID(args.id);
            const {password: _, ...safe} = user as any;
            return {content: [{type: 'text', text: JSON.stringify(safe)}]};
        } catch (error: unknown) {
            logger.error(`MCP get_user error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: User not found`}], isError: true};
        }
    });

    server.registerTool('create_user', {
        description: 'Create a new docPouch user. Admin only. If password is not provided, one is generated and must be delivered via email; when SMTP is unavailable this fails unless PASSWORD_IN_RESPONSE=true is set (then the password is returned in the response).',
        inputSchema: CreateUserSchema,
    }, async (args) => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const isAdmin = await dataManager.isAdmin(userid);
            if (!isAdmin) {
                return {content: [{type: 'text', text: 'Error: admin access required'}], isError: true};
            }
            const autoGenerated = !args.password;
            // #114: an auto-generated password must be delivered out of band.
            // Without SMTP (or an email address) and without the explicit
            // PASSWORD_IN_RESPONSE opt-in, creation fails before the account
            // is written.
            if (autoGenerated && !passwordInResponseAllowed()
                && (!args.email || !emailService.isConfigured())) {
                return {
                    content: [{
                        type: 'text',
                        text: 'Error: password delivery is unavailable (SMTP not configured or no email address). Configure SMTP, provide an email address, or set PASSWORD_IN_RESPONSE=true.'
                    }],
                    isError: true
                };
            }
            const password = args.password || generatePassword();
            const inputObj = {
                name: args.name,
                password,
                email: args.email,
                department: args.department,
                group: args.group,
                isAdmin: args.isAdmin,
                ...(args.role !== undefined ? {role: args.role} : {}),
            };
            const validated = validator.getValidatedObject('userCreation', inputObj);
            if (!validated) {
                return {content: [{type: 'text', text: 'Error: validation failed'}], isError: true};
            }
            const newUser = await dataManager.createUser(validated as any);
            const {password: _, ...safe} = newUser as any;

            if (args.email) {
                const emailResult = await emailService.sendWelcomeEmail(args.email, args.name, password);
                if (emailResult.sent) {
                    return {
                        content: [{
                            type: 'text',
                            text: JSON.stringify({...safe, message: `Password sent to ${args.email}`})
                        }]
                    };
                }
                if (!autoGenerated) {
                    // The caller chose the password themselves, so delivery
                    // is not required.
                    return {
                        content: [{
                            type: 'text',
                            text: JSON.stringify({...safe, message: 'Email delivery failed; the password was not emailed to the user.'})
                        }]
                    };
                }
                if (passwordInResponseAllowed()) {
                    return {
                        content: [{
                            type: 'text',
                            text: JSON.stringify({
                                ...safe,
                                password,
                                message: 'Email delivery failed; password shown as fallback'
                            })
                        }]
                    };
                }
                // Auto-generated password could not be delivered: roll the
                // account back.
                await dataManager.removeUser(newUser._id).catch(() => undefined);
                logger.error(`MCP create_user: rolled back creation of ${newUser._id}; password email could not be delivered.`);
                return {
                    content: [{
                        type: 'text',
                        text: 'Error: email delivery failed, so the account was not created. Fix the SMTP configuration or set PASSWORD_IN_RESPONSE=true.'
                    }],
                    isError: true
                };
            }
            if (!autoGenerated) {
                return {
                    content: [{
                        type: 'text',
                        text: JSON.stringify({...safe, message: 'User created. The password you provided was not emailed.'})
                    }]
                };
            }
            // Auto-generated without an email address: only reachable with
            // the explicit opt-in (see the pre-check above).
            return {
                content: [{
                    type: 'text',
                    text: JSON.stringify({
                        ...safe,
                        password,
                        message: 'No email address provided; password shown as fallback'
                    })
                }]
            };
        } catch (error: unknown) {
            logger.error(`MCP create_user error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('update_user', {
        description: 'Update a docPouch user. Non-admins can update their own profile (but not the isAdmin field). Admins can update any user. Password changes are not supported via this tool; use admin_reset_password instead.',
        inputSchema: UpdateUserSchema,
    }, async (args) => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const isAdmin = await dataManager.isAdmin(userid);
            if (!isAdmin && args.id !== userid) {
                return {content: [{type: 'text', text: 'Error: can only update your own profile'}], isError: true};
            }
            if (!isAdmin && (args.isAdmin !== undefined || args.role !== undefined)) {
                return {
                    content: [{type: 'text', text: 'Error: super-admin access required to change isAdmin or role'}],
                    isError: true
                };
            }
            const inputObj: Record<string, unknown> = {};
            if (args.name !== undefined) inputObj.name = args.name;
            if (args.email !== undefined) inputObj.email = args.email;
            if (args.department !== undefined) inputObj.department = args.department;
            if (args.group !== undefined) inputObj.group = args.group;
            if (args.isAdmin !== undefined) inputObj.isAdmin = args.isAdmin;
            if (args.role !== undefined) inputObj.role = args.role;

            const validated = validator.getValidatedObject('userUpdate', inputObj);
            if (!validated) {
                return {content: [{type: 'text', text: 'Error: validation failed'}], isError: true};
            }
            const result = await dataManager.updateUser(args.id, validated as any);
            return {content: [{type: 'text', text: JSON.stringify({updated: result})}]};
        } catch (error: unknown) {
            logger.error(`MCP update_user error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('admin_reset_password', {
        description: 'Reset a user\'s password. Admin only. A new random password is generated and sent to the user\'s email address. If email delivery is unavailable, the reset is refused (or returned in the response as a fallback when PASSWORD_IN_RESPONSE=true is set).',
        inputSchema: AdminResetPasswordSchema,
    }, async (args) => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const isAdmin = await dataManager.isAdmin(userid);
            if (!isAdmin) {
                return {content: [{type: 'text', text: 'Error: admin access required'}], isError: true};
            }
            const user = await dataManager.getUserByID(args.id);
            if (!user) {
                return {content: [{type: 'text', text: 'Error: user not found'}], isError: true};
            }

            const userEmail = (user as any).email;
            // #114: without a way to deliver the new password, refuse before
            // touching anything — unless the operator explicitly opted in to
            // the response fallback.
            if (!passwordInResponseAllowed() && (!userEmail || !emailService.isConfigured())) {
                return {
                    content: [{
                        type: 'text',
                        text: 'Error: password delivery is unavailable (SMTP not configured or no email address). Configure SMTP, set an email address on the account, or set PASSWORD_IN_RESPONSE=true.'
                    }],
                    isError: true
                };
            }

            const oldHash = (user as any).password;
            const newPassword = generatePassword();
            await dataManager.updateUser(args.id, {password: newPassword});

            if (userEmail) {
                const emailResult = await emailService.sendPasswordResetEmail(userEmail, (user as any).name, newPassword);
                if (emailResult.sent) {
                    return {
                        content: [{
                            type: 'text',
                            text: JSON.stringify({message: `New password sent to ${userEmail}`})
                        }]
                    };
                }
                if (passwordInResponseAllowed()) {
                    return {
                        content: [{
                            type: 'text',
                            text: JSON.stringify({
                                password: newPassword,
                                message: 'Email delivery failed; password shown as fallback'
                            })
                        }]
                    };
                }
                // Delivery failed and the fallback is not allowed: restore
                // the previous password and report.
                await dataManager.users.update(args.id, {password: oldHash}).catch(() => undefined);
                logger.error(`MCP admin_reset_password: rolled back password reset for ${args.id}; password email could not be delivered.`);
                return {
                    content: [{
                        type: 'text',
                        text: 'Error: email delivery failed; the password was NOT changed. Fix the SMTP configuration or set PASSWORD_IN_RESPONSE=true.'
                    }],
                    isError: true
                };
            }
            // Only reachable with the explicit opt-in (see the pre-check).
            return {
                content: [{
                    type: 'text',
                    text: JSON.stringify({
                        password: newPassword,
                        message: 'No email address on file; password shown as fallback'
                    })
                }]
            };
        } catch (error: unknown) {
            logger.error(`MCP admin_reset_password error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('delete_user', {
        description: 'Delete a docPouch user by ID. Admin only.',
        inputSchema: DeleteUserSchema,
    }, async (args) => {
        const userid = getUserId();
        if (!userid) {
            return {content: [{type: 'text', text: 'Error: not authenticated'}], isError: true};
        }
        try {
            const isAdmin = await dataManager.isAdmin(userid);
            if (!isAdmin) {
                return {content: [{type: 'text', text: 'Error: admin access required'}], isError: true};
            }
            await dataManager.removeUser(args.id);
            return {content: [{type: 'text', text: JSON.stringify({deleted: true})}]};
        } catch (error: unknown) {
            logger.error(`MCP delete_user error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('forgot_password', {
        description: 'Request a password reset email for a user by their email address (calling MCP tools requires authentication). Always returns a generic success message to prevent email enumeration.',
        inputSchema: ForgotPasswordSchema,
    }, async (args) => {
        try {
            const user = await dataManager.getUserByEmail(args.email);
            if (user) {
                // #110: only the raw token is passed; EmailService builds the
                // link from its trusted, configured base URL. The previous
                // code passed a full URL (doubly concatenated by
                // EmailService) with a hardcoded localhost fallback.
                const token = await dataManager.createPasswordResetToken(user._id);
                await emailService.sendForgotPasswordEmail(args.email, (user as any).name, token);
            }
            return {
                content: [{
                    type: 'text',
                    text: JSON.stringify({message: 'If an account with that email exists, a reset link has been sent.'})
                }]
            };
        } catch (error: unknown) {
            logger.error(`MCP forgot_password error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });

    server.registerTool('reset_password', {
        description: 'Reset a user password using a single-use token received via email from forgot_password. Tokens expire after one hour.',
        inputSchema: ResetPasswordSchema,
    }, async (args) => {
        try {
            const userId = await dataManager.consumePasswordResetToken(args.token);
            if (!userId) {
                return {content: [{type: 'text', text: 'Error: Invalid or expired reset token'}], isError: true};
            }
            await dataManager.updateUser(userId, {password: args.password});
            return {content: [{type: 'text', text: JSON.stringify({message: 'Password reset successful'})}]};
        } catch (error: unknown) {
            logger.error(`MCP reset_password error: ${getErrorMessage(error)}`);
            return {content: [{type: 'text', text: `Error: ${getErrorMessage(error)}`}], isError: true};
        }
    });
}